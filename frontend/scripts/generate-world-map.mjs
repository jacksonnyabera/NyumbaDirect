// Generates src/assets/worldMapData.js: a lightweight static SVG world map.
//
// Data: Natural Earth 1:110m via the `world-atlas` package (public domain).
// This is a one-off build-time step; nothing here ships to the browser and the
// app makes no map-tile or third-party requests at runtime.
//
// Usage (from frontend/, packages are intentionally NOT added to package.json):
//   npm i --no-save d3-geo topojson-client world-atlas
//   node scripts/generate-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature, merge } from "topojson-client";

const WIDTH = 1000;
const HEIGHT = 500;
const topo = JSON.parse(
  readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"),
);

const countries = topo.objects.countries.geometries;
// Antarctica (010) is dropped: it adds weight and no meaning for this map.
const land = merge(topo, countries.filter((c) => c.id !== "010"));
const kenyaGeometry = countries.find((c) => c.id === "404");
if (!kenyaGeometry) throw new Error("Kenya (404) not found in dataset");
const kenya = feature(topo, kenyaGeometry);

const projection = geoNaturalEarth1().fitExtent(
  [[8, 8], [WIDTH - 8, HEIGHT - 8]],
  land,
);
const path = geoPath(projection).digits(1);

const [nairobiX, nairobiY] = projection([36.8219, -1.2921]); // Nairobi, lon/lat

const out = `// GENERATED by scripts/generate-world-map.mjs. Do not edit by hand.
// Source: Natural Earth 1:110m (public domain) via world-atlas.
export const MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";
export const LAND_PATH = ${JSON.stringify(path(land))};
export const KENYA_PATH = ${JSON.stringify(path(kenya))};
export const KENYA_POINT = { x: ${nairobiX.toFixed(1)}, y: ${nairobiY.toFixed(1)} };
`;
writeFileSync("src/assets/worldMapData.js", out);
console.log("bytes:", out.length, "land:", path(land).length, "kenya:", path(kenya).length);
